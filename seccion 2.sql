-- EJERCICIO 6
-- Mostrar el titulo del libro y el nombre y apellido de su autor.

SELECT L.TITULO,
       A.NOMBRES,
       A.APELLIDOS
FROM LIBROS L
INNER JOIN AUTORES A
    ON L.RUT_AUTOR = A.RUT_AUTOR;


-- EJERCICIO 7
-- Mostrar fecha del prestamo, estudiante, libro y funcionario.

SELECT P.FECHA_P,
       CONCAT(E.NOMBRES, ' ', E.APELLIDOS) AS ESTUDIANTE,
       L.TITULO AS LIBRO,
       CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS FUNCIONARIO
FROM PRESTAMO P
INNER JOIN ESTUDIANTES E
    ON P.RUT_EST = E.RUT_EST
INNER JOIN LIBROS L
    ON P.COD_LIBRO = L.COD_LIBRO
INNER JOIN FUNCIONARIOS F
    ON P.RUT_FUNC = F.RUT_FUNC;


-- EJERCICIO 8
-- Mostrar estudiante, carrera y ciudad donde estudia.

SELECT CONCAT(E.NOMBRES, ' ', E.APELLIDOS) AS ESTUDIANTE,
       CA.NOMBRE AS CARRERA,
       CI.NOMBRE AS CIUDAD
FROM ESTUDIANTES E
INNER JOIN CARRERAS CA
    ON E.ID_CARRERA = CA.ID_CARRERA
INNER JOIN CAMPUS C
    ON CA.ID_CAMPUS = C.ID_CAMPUS
INNER JOIN CIUDAD CI
    ON C.ID_CIUDAD = CI.ID_CIUDAD;


-- EJERCICIO 9
-- Mostrar titulo del libro, editorial y pais de origen.

SELECT L.TITULO,
       ED.NOMBRE AS EDITORIAL,
       ED.PAIS
FROM LIBROS L
INNER JOIN EDITORIALES ED
    ON L.ID_EDIT = ED.ID_EDIT;


-- EJERCICIO 10
-- Mostrar titulo del libro y biblioteca donde se encuentra.

SELECT L.TITULO,
       B.BIBLIOTECA
FROM LIBROS L
INNER JOIN BIBLIOTECA B
    ON L.ID_BIBLIO = B.ID_BIBLIO;


