
USE BIBLIOTECA;

-- EJERCICIO 1
-- Mostrar el título y año de los libros,
-- ordenados del más antiguo al más nuevo.

SELECT TITULO, AGNO
FROM LIBROS
ORDER BY AGNO ASC;


-- EJERCICIO 2
-- Estudiantes mayores de 25 años.

SELECT NOMBRES, APELLIDOS, EDAD
FROM ESTUDIANTES
WHERE EDAD > 25;


-- EJERCICIO 3
-- Libros de la editorial con ID 3.

SELECT TITULO, AGNO
FROM LIBROS
WHERE ID_EDIT = 3;


-- EJERCICIO 4
-- Autores cuyo apellido comienza con M.

SELECT *
FROM AUTORES
WHERE APELLIDOS LIKE 'M%';


-- EJERCICIO 5
-- Funcionarios cuya salud sea distinta de Buena.

SELECT NOMBRES, APELLIDOS
FROM FUNCIONARIOS
WHERE SALUD <> 'Buena';




