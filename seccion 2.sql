-- EJERCICIO 11
-- Cantidad de libros por tipo.

SELECT T.TIPO_P,
       COUNT(L.COD_LIBRO) AS CANTIDAD_LIBROS
FROM TIPO T
LEFT JOIN LIBROS L
    ON T.ID_TIPO = L.ID_TIPO
GROUP BY T.ID_TIPO, T.TIPO_P;


-- EJERCICIO 12
-- Edad promedio de estudiantes por carrera.

SELECT C.NOMBRE AS CARRERA,
       ROUND(AVG(E.EDAD), 2) AS EDAD_PROMEDIO
FROM CARRERAS C
LEFT JOIN ESTUDIANTES E
    ON C.ID_CARRERA = E.ID_CARRERA
GROUP BY C.ID_CARRERA, C.NOMBRE;


-- EJERCICIO 13
-- Nombre del funcionario y cantidad de prestamos,
-- ordenados de mayor a menor.

SELECT CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS FUNCIONARIO,
       COUNT(P.COD_LIBRO) AS TOTAL_PRESTAMOS
FROM FUNCIONARIOS F
LEFT JOIN PRESTAMO P
    ON F.RUT_FUNC = P.RUT_FUNC
GROUP BY F.RUT_FUNC, F.NOMBRES, F.APELLIDOS
ORDER BY TOTAL_PRESTAMOS DESC;


-- EJERCICIO 14
-- Autores con mas de un libro registrado.

SELECT A.NOMBRES,
       A.APELLIDOS,
       COUNT(L.COD_LIBRO) AS CANTIDAD_LIBROS
FROM AUTORES A
INNER JOIN LIBROS L
    ON A.RUT_AUTOR = L.RUT_AUTOR
GROUP BY A.RUT_AUTOR, A.NOMBRES, A.APELLIDOS
HAVING COUNT(L.COD_LIBRO) > 1;


-- EJERCICIO 15
-- Nombre de la ciudad y cantidad de estudiantes.

SELECT CI.NOMBRE AS CIUDAD,
       COUNT(E.RUT_EST) AS CANTIDAD_ESTUDIANTES
FROM CIUDAD CI
LEFT JOIN CAMPUS C
    ON CI.ID_CIUDAD = C.ID_CIUDAD
LEFT JOIN CARRERAS CA
    ON C.ID_CAMPUS = CA.ID_CAMPUS
LEFT JOIN ESTUDIANTES E
    ON CA.ID_CARRERA = E.ID_CARRERA
GROUP BY CI.ID_CIUDAD, CI.NOMBRE;


