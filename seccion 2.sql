-- EJERCICIO 16
-- Mostrar el libro mas antiguo de la biblioteca.

SELECT TITULO, AGNO
FROM LIBROS
WHERE AGNO = (
    SELECT MIN(AGNO)
    FROM LIBROS
);


-- EJERCICIO 17
-- Listar estudiantes que nunca pidieron un libro prestado.

SELECT E.*
FROM ESTUDIANTES E
WHERE NOT EXISTS (
    SELECT 1
    FROM PRESTAMO P
    WHERE P.RUT_EST = E.RUT_EST
);


-- EJERCICIO 18
-- Mostrar los libros que nunca fueron prestados.

SELECT L.TITULO
FROM LIBROS L
WHERE NOT EXISTS (
    SELECT 1
    FROM PRESTAMO P
    WHERE P.COD_LIBRO = L.COD_LIBRO
);


-- EJERCICIO 19
-- Mostrar los prestamos realizados el mes anterior.

SELECT *
FROM PRESTAMO
WHERE FECHA_P >= DATE_FORMAT(
    CURRENT_DATE - INTERVAL 1 MONTH,
    '%Y-%m-01'
)
AND FECHA_P < DATE_FORMAT(
    CURRENT_DATE,
    '%Y-%m-01'
);


-- EJERCICIO 20
-- Mostrar los 3 libros mas prestados.

SELECT L.TITULO,
       COUNT(P.COD_LIBRO) AS TOTAL_PRESTAMOS
FROM LIBROS L
INNER JOIN PRESTAMO P
    ON L.COD_LIBRO = P.COD_LIBRO
GROUP BY L.COD_LIBRO, L.TITULO
ORDER BY TOTAL_PRESTAMOS DESC
LIMIT 3;
