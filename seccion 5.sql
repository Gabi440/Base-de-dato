USE BIBLIOTECA;

CREATE TABLE AUDITORIA_PRESTAMOS (
    ID_AUDITORIA INT AUTO_INCREMENT PRIMARY KEY,
    RUT_EST VARCHAR(15) NOT NULL,
    COD_LIBRO INT NOT NULL,
    FECHA_REGISTRO DATETIME NOT NULL,
    ACCION VARCHAR(50) NOT NULL
);

CREATE TRIGGER TR_AUDITAR_PRESTAMO
AFTER INSERT ON PRESTAMO
FOR EACH ROW
INSERT INTO AUDITORIA_PRESTAMOS
    (RUT_EST, COD_LIBRO, FECHA_REGISTRO, ACCION)
VALUES
    (NEW.RUT_EST, NEW.COD_LIBRO, NOW(), 'NUEVO PRESTAMO');

