CREATE VIEW VW_LIBROS_POR_BIBLIOTECA AS
SELECT
    B.BIBLIOTECA,
    COUNT(L.COD_LIBRO) AS CANTIDAD_LIBROS
FROM BIBLIOTECA B
LEFT JOIN LIBROS L
    ON B.ID_BIBLIO = L.ID_BIBLIO
GROUP BY B.ID_BIBLIO, B.BIBLIOTECA;

SELECT * FROM VW_LIBROS_POR_BIBLIOTECA;










